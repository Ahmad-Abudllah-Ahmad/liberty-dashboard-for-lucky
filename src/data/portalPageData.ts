import type { MonitorMachine, MonitorRow } from '../components/scada/SplitMonitor';

const D = '9/30/2026 9:00:31 PM';
const T = '10/1/2026 11:28:34 AM';

const q = (
  label: string,
  unit: string,
  setValue: string | number,
  value: string | number,
  difference: string | number,
  tone: MonitorRow['tone'] = 'ok',
  date = D,
  tolerance: string | number = 5
): MonitorRow => ({ label, date, tolerance, unit, setValue, value, difference, tone });

const tag = (
  label: string,
  tagNo: string | number,
  unit: string,
  value: string | number,
  date = T,
  tone?: MonitorRow['tone']
): MonitorRow => ({ label, tag: tagNo, date, unit, value, tone });

const diffOf = (set: number, act: number) => Number((act - set).toFixed(1));
const toneOf = (set: number, act: number): MonitorRow['tone'] =>
  set === 0 ? (Math.abs(act) < 0.05 ? 'ok' : 'bad') : Math.abs(act - set) / Math.abs(set) <= 0.05 ? 'ok' : 'bad';

