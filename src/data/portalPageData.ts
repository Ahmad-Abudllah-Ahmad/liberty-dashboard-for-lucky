const stenterLiveRows = (
  tagStart: number,
  speedAct: number,
  speedSet: number,
  burnerPeak: number,
  options?: { chambers?: number; moisture?: number; date?: string },
): MonitorRow[] => {
  const chambers = options?.chambers ?? 8;
  const running = speedAct > 0;
  const date = options?.date ?? D;
  const moisture = options?.moisture ?? (running ? 4.8 : 0);
  const rows: MonitorRow[] = [
    tag('Speed', tagStart, 'M/MIN', speedAct, date),
    tag('Speed Set', tagStart + 1, 'M/MIN', speedSet, date),
    tag('Exit Moisture', tagStart + 2, '%', moisture, date),
    tag('Moisture Set', tagStart + 3, '%', 5.0, date),
    tag('Line Tension', tagStart + 4, 'N', running ? 124 : 0, date),
    tag('Weft Straightener', tagStart + 5, '%', running ? 88 : 0, date),
    tag('Overfeed', tagStart + 6, '%', running ? 12 : 0, date),
    tag('Panel Temp. 1', tagStart + 7, '°C', running ? 29.2 : 31.5, date),
    tag('Panel Temp. 2', tagStart + 8, '°C', running ? 33.1 : 34.8, date),
  ];
  for (let i = 0; i < chambers; i++) {
    const act = running
      ? Number((burnerPeak + (i < chambers / 2 ? i * 0.85 : (chambers - 1 - i) * 0.55)).toFixed(1))
      : Number((36 + i * 0.5).toFixed(1));
    rows.push(tag(`Burner ${String(i + 1).padStart(2, '0')}`, tagStart + 30 + i, '°C', act, date));
  }
  rows.push(
    tag('Exhaust 01', tagStart + 50, '%', running ? 48 : 0, date),
    tag('Exhaust 02', tagStart + 51, '%', running ? 40 : 0, date),
    tag('Circulation Fan 01', tagStart + 52, '%', running ? 100 : 0, date),
    tag('Circulation Fan 02', tagStart + 53, '%', running ? 98 : 0, date),
    tag('Circulation Fan 03', tagStart + 54, '%', running ? 100 : 0, date),
  );
  return rows;
};

