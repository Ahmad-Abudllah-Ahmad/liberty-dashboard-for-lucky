const stenterQuality = (
  speedSet: number,
  speedAct: number,
  burnerSet: number,
  burnerAct: number,
  extra: MonitorRow[] = [],
): MonitorRow[] => {
  const running = speedAct > 0;
  const burners = Array.from({ length: 8 }, (_, index) => {
    const act = Number((burnerAct + (index % 2 === 0 ? -index * 0.4 : index * 0.3)).toFixed(1));
    return q(`Burner 0${index + 1}`, '°C', burnerSet, act, diffOf(burnerSet, act), toneOf(burnerSet, act));
  });
  return [
    q('Speed', 'M/MIN', speedSet, speedAct, diffOf(speedSet, speedAct), toneOf(speedSet, speedAct)),
    ...extra,
    ...burners,
    q('Exhaust 01', '%', 50, running ? 48 : 0, running ? -2 : -50, running ? 'ok' : 'bad'),
    q('Exhaust 02', '%', 40, running ? 40 : 0, running ? 0 : -40, running ? 'ok' : 'bad'),
    q('Hot Air Circulate Fan 01', '%', 100, running ? 100 : 0, running ? 0 : -100, running ? 'ok' : 'bad'),
    q('Hot Air Circulate Fan 02', '%', 100, running ? 98 : 0, running ? -2 : -100, running ? 'ok' : 'bad'),
    q('Hot Air Circulate Fan 03', '%', 100, running ? 100 : 0, running ? 0 : -100, running ? 'ok' : 'bad'),
  ];
};

